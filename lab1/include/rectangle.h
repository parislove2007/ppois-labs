#pragma once

#include <iosfwd>
#include "point.h"

/**
 * @brief Прямоугольник со сторонами, параллельными осям координат.
 *
 * Задаётся двумя вершинами: левой нижней и правой верхней.
 * Координаты целочисленные.
 *
 * Отдельным состоянием является пустой прямоугольник — результат
 * пересечения непересекающихся прямоугольников. Создаётся методом
 * empty(), распознаётся методом isEmpty(). Изменяющие операции
 * над пустым прямоугольником ничего не делают.
 */
class Rectangle
{
public:
    /**
     * @brief Создаёт прямоугольник по двум противоположным вершинам.
     * @param bottomLeft Левая нижняя вершина.
     * @param topRight Правая верхняя вершина.
     */
    Rectangle(Point bottomLeft, Point topRight);

    /**
     * @brief Создаёт пустой прямоугольник.
     * @return Прямоугольник, для которого isEmpty() возвращает true.
     */
    static Rectangle empty();

    /** @return true, если прямоугольник пуст. */
    bool isEmpty() const;

    /** @return Координата левой стороны по горизонтальной оси. */
    int left() const;

    /** @return Координата правой стороны по горизонтальной оси. */
    int right() const;

    /** @return Координата нижней стороны по вертикальной оси. */
    int bottom() const;

    /** @return Координата верхней стороны по вертикальной оси. */
    int top() const;

    /** @return Левая нижняя вершина. */
    Point bottomLeft() const;

    /** @return Правая нижняя вершина. */
    Point bottomRight() const;

    /** @return Правая верхняя вершина. */
    Point topRight() const;

    /** @return Левая верхняя вершина. */
    Point topLeft() const;

    /**
     * @brief Сравнивает прямоугольники на равенство.
     *
     * Два пустых прямоугольника считаются равными независимо
     * от хранимых координат. Пустой и непустой не равны никогда.
     * @param other Прямоугольник для сравнения.
     * @return true, если обе вершины совпадают.
     */
    bool operator==(const Rectangle& other) const;

    /**
     * @brief Перемещает прямоугольник на заданный сдвиг.
     *
     * Размер не меняется. Для пустого прямоугольника не делает ничего.
     * @param deltaX Сдвиг по горизонтальной оси.
     * @param deltaY Сдвиг по вертикальной оси.
     */
    void move(int deltaX, int deltaY);

    /**
     * @brief Задаёт новые размеры, оставляя левую нижнюю вершину на месте.
     *
     * Для пустого прямоугольника не делает ничего.
     * @param width Новая ширина.
     * @param height Новая высота.
     * @throws std::invalid_argument Если ширина или высота отрицательна.
     */
    void resize(int width, int height);

    /**
     * @brief Увеличивает размер на единицу по каждой оси (префиксная форма).
     *
     * Сдвигается только правая верхняя вершина. Для пустого
     * прямоугольника не делает ничего.
     * @return Ссылка на изменённый прямоугольник.
     */
    Rectangle& operator++();

    /**
     * @brief Увеличивает размер на единицу по каждой оси (постфиксная форма).
     * @return Копия прямоугольника до увеличения.
     */
    Rectangle operator++(int);

    /**
     * @brief Уменьшает размер на единицу по каждой оси (префиксная форма).
     *
     * Для пустого прямоугольника не делает ничего.
     * @return Ссылка на изменённый прямоугольник.
     * @throws std::invalid_argument Если размер стал бы отрицательным.
     */
    Rectangle& operator--();

    /**
     * @brief Уменьшает размер на единицу по каждой оси (постфиксная форма).
     * @return Копия прямоугольника до уменьшения.
     * @throws std::invalid_argument Если размер стал бы отрицательным.
     */
    Rectangle operator--(int);

    /**
     * @brief Заменяет прямоугольник наименьшим, содержащим его и другой.
     *
     * Пустой прямоугольник нейтрален: объединение с ним ничего не меняет.
     * @param other Второй прямоугольник.
     * @return Ссылка на изменённый прямоугольник.
     */
    Rectangle& operator+=(const Rectangle& other);

    /**
     * @brief Строит наименьший прямоугольник, содержащий оба заданных.
     * @param other Второй прямоугольник.
     * @return Новый прямоугольник; операнды не изменяются.
     */
    Rectangle operator+(const Rectangle& other) const;

    /**
     * @brief Заменяет прямоугольник его пересечением с другим.
     *
     * Если прямоугольники не пересекаются или один из них пуст,
     * результатом становится пустой прямоугольник.
     * @param other Второй прямоугольник.
     * @return Ссылка на изменённый прямоугольник.
     */
    Rectangle& operator-=(const Rectangle& other);

    /**
     * @brief Строит пересечение двух прямоугольников.
     * @param other Второй прямоугольник.
     * @return Пересечение или пустой прямоугольник; операнды не изменяются.
     */
    Rectangle operator-(const Rectangle& other) const;

private:
    Point bottomLeft_;
    Point topRight_;
    bool isEmpty_;
};

/**
 * @brief Записывает прямоугольник в поток.
 *
 * Непустой выводится как четыре числа "left bottom right top",
 * пустой — как слово "empty".
 * @param out Поток вывода.
 * @param rectangle Записываемый прямоугольник.
 * @return Ссылка на поток.
 */
std::ostream& operator<<(std::ostream& out, const Rectangle& rectangle);

/**
 * @brief Читает прямоугольник из потока в формате "left bottom right top".
 *
 * При некорректном вводе поток переводится в состояние ошибки,
 * а прямоугольник остаётся неизменным. Слово "empty" не читается.
 * @param in Поток ввода.
 * @param rectangle Прямоугольник, который будет заполнен.
 * @return Ссылка на поток.
 */
std::istream& operator>>(std::istream& in, Rectangle& rectangle);