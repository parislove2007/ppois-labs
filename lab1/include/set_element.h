#pragma once

#include <iosfwd>
#include <string>

class Set;

/**
 * @brief Элемент множества: либо атом, либо вложенное множество.
 *
 * Атом хранится как строка, вложенное множество — как указатель
 * на объект в динамической памяти. Указатель позволяет типу
 * ссылаться на себя: множество содержит элементы, элемент может
 * содержать множество.
 *
 * Класс владеет вложенным множеством, поэтому реализует правило
 * трёх: конструктор копирования, копирующее присваивание
 * и деструктор. Копирование глубокое — копии независимы.
 */
class SetElement
{
public:
    /**
     * @brief Создаёт элемент-атом.
     * @param atom Значение атома.
     */
    explicit SetElement(const std::string& atom);

    /**
     * @brief Создаёт элемент-множество.
     *
     * Переданное множество копируется в динамическую память,
     * элемент становится владельцем копии.
     * @param nested Вложенное множество.
     */
    explicit SetElement(const Set& nested);

    /**
     * @brief Конструктор копирования с глубоким копированием.
     *
     * Для элемента-множества выделяет собственную память, поэтому
     * копия не разделяет данные с оригиналом.
     * @param other Копируемый элемент.
     */
    SetElement(const SetElement& other);

    /**
     * @brief Копирующее присваивание с глубоким копированием.
     *
     * Освобождает прежнее вложенное множество перед копированием.
     * Безопасно при самоприсваивании.
     * @param other Присваиваемый элемент.
     * @return Ссылка на изменённый элемент.
     */
    SetElement& operator=(const SetElement& other);

    /** @brief Освобождает вложенное множество, если оно есть. */
    ~SetElement();

    /** @return true, если элемент является атомом. */
    bool isAtom() const;

    /**
     * @brief Возвращает значение атома.
     * @return Значение атома; для элемента-множества — пустая строка.
     */
    const std::string& atom() const;

    /**
     * @brief Возвращает вложенное множество.
     * @pre Элемент не является атомом, то есть isAtom() == false.
     * @return Ссылка на вложенное множество.
     */
    const Set& nested() const;

    /**
     * @brief Сравнивает элементы на равенство.
     *
     * Атом и множество не равны никогда. Два атома сравниваются
     * по значению, два множества — рекурсивно, без учёта порядка.
     * @param other Элемент для сравнения.
     * @return true, если элементы совпадают.
     */
    bool operator==(const SetElement& other) const;

private:
    std::string atom_;
    Set* nested_;
};

/**
 * @brief Записывает элемент в поток.
 *
 * Атом выводится как его значение, вложенное множество —
 * рекурсивно в фигурных скобках.
 * @param out Поток вывода.
 * @param element Записываемый элемент.
 * @return Ссылка на поток.
 */
std::ostream& operator<<(std::ostream& out, const SetElement& element);