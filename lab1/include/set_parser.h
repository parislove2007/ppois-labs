#pragma once

#include <cstddef>
#include <string>
#include "set.h"

/**
 * @brief Разбор множества из текстового представления.
 *
 * Понимает записи вида "{a, b, {a, b}, {}, {a, {c}}}": фигурные
 * скобки ограничивают множество, элементы разделяются запятыми,
 * вложенность произвольная. Пробелы между лексемами игнорируются.
 *
 * Реализован методом рекурсивного спуска: разбор множества
 * вызывает разбор элемента, а тот для вложенных скобок снова
 * вызывает разбор множества.
 *
 * Класс не имеет состояния, все методы статические.
 */
class SetParser
{
public:
    /**
     * @brief Строит множество по его текстовому представлению.
     * @param text Разбираемая строка.
     * @return Разобранное множество.
     * @throws std::invalid_argument При любой синтаксической ошибке:
     *         отсутствии скобок, пустом элементе или лишних
     *         символах после закрывающей скобки.
     */
    static Set parse(const std::string& text);

private:
    /**
     * @brief Разбирает множество, начиная с открывающей скобки.
     * @param text Разбираемая строка.
     * @param position Текущая позиция; сдвигается за закрывающую скобку.
     * @return Разобранное множество.
     * @throws std::invalid_argument Если скобка не открыта, не закрыта
     *         или вместо разделителя встречен посторонний символ.
     */
    static Set parseSet(const std::string& text, std::size_t& position);

    /**
     * @brief Разбирает один элемент: атом или вложенное множество.
     * @param text Разбираемая строка.
     * @param position Текущая позиция; сдвигается за конец элемента.
     * @return Разобранный элемент.
     * @throws std::invalid_argument Если элемент пуст или вложенное
     *         множество записано неверно.
     */
    static SetElement parseElement(const std::string& text, std::size_t& position);

    /**
     * @brief Читает имя атома до разделителя.
     *
     * Разделителями считаются запятая, закрывающая скобка и пробел.
     * @param text Разбираемая строка.
     * @param position Текущая позиция; сдвигается за конец имени.
     * @return Прочитанное имя.
     * @throws std::invalid_argument Если имя оказалось пустым.
     */
    static std::string parseAtom(const std::string& text, std::size_t& position);

    /**
     * @brief Пропускает подряд идущие пробелы.
     * @param text Разбираемая строка.
     * @param position Текущая позиция; сдвигается на первый непробельный символ.
     */
    static void skipSpaces(const std::string& text, std::size_t& position);
};