#pragma once

#include <string>

namespace repair
{

/**
 * @brief Состояние заказа-наряда.
 *
 * Перечисление, а не класс: у состояния нет ни полей, ни поведения,
 * а допустимые переходы между состояниями описаны в RepairOrder.
 */
enum class OrderStatus
{
    Accepted,          ///< Устройство принято, диагностика не проводилась.
    Diagnosed,         ///< Диагностика выполнена, смета составлена.
    EstimateApproved,  ///< Клиент утвердил смету.
    InRepair,          ///< Ремонт выполняется.
    Completed,         ///< Работы завершены, устройство ждёт выдачи.
    Issued,            ///< Устройство выдано клиенту.
    Cancelled          ///< Заказ отменён.
};

/**
 * @brief Переводит состояние в название для документов и сообщений.
 * @param status Состояние заказа.
 * @return Название состояния на русском языке.
 */
std::string toString(OrderStatus status);

}
